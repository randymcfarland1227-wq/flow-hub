// Build js/activity.js — the offline fallback for Flow's TickTick tracking.
//
//   TZ=America/New_York node tools/build_activity.mjs [--as-of YYYY-MM-DD]
//
// Reads Worker-shaped payloads in tools/ticktick_raw/ (feed.json = /api/ticktick/done,
// open.json = /api/ticktick/open) and runs them through js/ticktick.js — the same
// parser the site uses live — so the snapshot and the live view always agree.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { buildActivity, isoDay } = require(join(ROOT, 'js', 'ticktick.js'));

const src = readFileSync(join(ROOT, 'js', 'data.js'), 'utf8');
const routines = JSON.parse(src.match(/const SNAPSHOT_ROUTINES = (\[[\s\S]*?\]);\n/)[1]);
const feed = JSON.parse(readFileSync(join(ROOT, 'tools', 'ticktick_raw', 'feed.json'), 'utf8'));
const open = JSON.parse(readFileSync(join(ROOT, 'tools', 'ticktick_raw', 'open.json'), 'utf8'));
const i = process.argv.indexOf('--as-of');
const asOf = i > 0 ? process.argv[i + 1] : isoDay(new Date());

const { unmatched, ...activity } = buildActivity(feed, open, routines, asOf);
writeFileSync(join(ROOT, 'js', 'activity.js'),
  '// GENERATED by tools/build_activity.mjs — offline fallback only.\n' +
  '// Flow reads TickTick live through Life Hub\'s Worker; this is used when that isn\'t reachable.\n' +
  'const ACTIVITY = ' + JSON.stringify(activity) + ';\n');
console.log(`${Object.keys(activity.routines).length} routines · as of ${asOf}`);
if (unmatched.length) console.log('unmatched TickTick titles:', unmatched.join(' | '));
